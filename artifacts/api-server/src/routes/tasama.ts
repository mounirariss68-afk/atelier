router.get("/documents/:id/file", async (req, res) => {
  try {
    const [doc] = await db
      .select()
      .from(tasamaDocumentsTable)
      .where(eq(tasamaDocumentsTable.id, req.params.id));
    if (!doc) {
      res.status(404).json({ error: "document-not-found" });
      return;
    }
    const filePath = path.join(TASAMA_PDF_DIR, doc.storagePath);
    try {
      const buffer = await fs.readFile(filePath);
      res.setHeader("Content-Type", doc.mimeType);
      res.setHeader("Content-Disposition", contentDispositionFilename("inline", doc.filename));
      res.send(buffer);
    } catch (err) {
      res.status(404).json({
        error: "file-missing",
        message: `PDF not found on disk at ${filePath}. Run "pnpm --filter @workspace/scripts run generate:tasama-pdfs".`,
      });
    }
  } catch (err) {
    res.status(500).json({ error: (err as Error).message });
  }
});

