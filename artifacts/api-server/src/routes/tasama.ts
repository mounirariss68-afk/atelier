router.get("/summary", async (_req, res) => {
  try {
    const [clients, employees, latestRuns] = await Promise.all([
      db.select().from(tasamaClientsTable),
      db.select({ count: sql<number>`count(*)` }).from(tasamaEmployeesTable),
      db
        .select()
        .from(tasamaPayrollRunsTable)
        .orderBy(desc(tasamaPayrollRunsTable.periodYear), desc(tasamaPayrollRunsTable.periodMonth))
        .limit(3),
    ]);
    const totalEmployeeCount = Number(employees[0]?.count ?? 0);
    const totalMonthlyPayroll = clients.reduce((s, c) => s + c.monthlyPayrollGross, 0);
    res.json({
      clientCount: clients.length,
      employeeCount: totalEmployeeCount,
      totalMonthlyPayroll,
      latestPayrollRuns: latestRuns,
    });
  } catch (err) {
    res.status(500).json({ error: (err as Error).message });
  }
});

