router.post("/service-requests", async (req, res) => {
  try {
    const body = req.body ?? {};
    if (!body.clientId || !body.type || !body.titleEn || !body.titleAr) {
      res.status(400).json({ error: "missing-required-fields", required: ["clientId", "type", "titleEn", "titleAr"] });
      return;
    }
    const id = body.id ?? `sr-${Date.now()}-${Math.floor(Math.random() * 1000).toString().padStart(3, "0")}`;
    const now = new Date().toISOString().slice(0, 10);
    await db.insert(tasamaServiceRequestsTable).values({
      id,
      clientId: body.clientId,
      employeeId: body.employeeId ?? null,
      type: body.type,
      titleEn: body.titleEn,
      titleAr: body.titleAr,
      description: body.description ?? "",
      descriptionAr: body.descriptionAr ?? "",
      status: body.status ?? "submitted",
      priority: body.priority ?? "medium",
      requestedBy: body.requestedBy ?? "client-portal",
      requestedAt: body.requestedAt ?? now,
      assignedAgent: body.assignedAgent ?? null,
      completedAt: body.completedAt ?? null,
      payload: body.payload ?? {},
      slaTargetHours: body.slaTargetHours ?? 48,
    });
    const [created] = await db
      .select()
      .from(tasamaServiceRequestsTable)
      .where(eq(tasamaServiceRequestsTable.id, id));
    res.status(201).json({ serviceRequest: created });
  } catch (err) {
    res.status(500).json({ error: (err as Error).message });
  }
});

