router.get("/employees/:employeeId", async (req, res) => {
  try {
    const [employee] = await db
      .select()
      .from(tasamaEmployeesTable)
      .where(eq(tasamaEmployeesTable.id, req.params.employeeId));
    if (!employee) {
      res.status(404).json({ error: "employee-not-found" });
      return;
    }
    const [salary] = await db
      .select()
      .from(tasamaSalaryComponentsTable)
      .where(eq(tasamaSalaryComponentsTable.employeeId, employee.id));
    const [leave] = await db
      .select()
      .from(tasamaLeaveBalancesTable)
      .where(eq(tasamaLeaveBalancesTable.employeeId, employee.id));
    const eosb = await db
      .select()
      .from(tasamaEosbProvisionsTable)
      .where(eq(tasamaEosbProvisionsTable.employeeId, employee.id))
      .orderBy(desc(tasamaEosbProvisionsTable.periodYear), desc(tasamaEosbProvisionsTable.periodMonth))
      .limit(1);
    res.json({ employee, salary: salary ?? null, leaveBalance: leave ?? null, eosb: eosb[0] ?? null });
  } catch (err) {
    res.status(500).json({ error: (err as Error).message });
  }
});

